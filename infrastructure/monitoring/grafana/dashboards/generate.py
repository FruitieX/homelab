#!/usr/bin/env python3
"""Generate the provisioned Grafana dashboards.

The dashboards are code: edit home.py / lab.py (helpers in lib.py), then run

    python3 infrastructure/monitoring/grafana/dashboards/generate.py

and commit the regenerated JSON and kustomization.yaml. Edits made in the
Grafana UI are not saved back; use "Save as" to experiment, then port the
change here.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import home  # noqa: E402
import lab  # noqa: E402

DASHBOARDS = [
    lab.overview_dashboard(),
    home.energy_dashboard(),
    home.climate_dashboard(),
    home.devices_dashboard(),
    lab.services_dashboard(),
    lab.workloads_dashboard(),
    lab.hardware_dashboard(),
    lab.network_dashboard(),
    lab.logs_dashboard(),
    lab.apps_dashboard(),
]

HEADER = """# Generated by generate.py; do not edit by hand.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
generatorOptions:
  disableNameSuffixHash: true
  labels:
    grafana_dashboard: "1"
  annotations:
    # Dashboards use ${...} variables of their own.
    kustomize.toolkit.fluxcd.io/substitute: disabled
configMapGenerator:
"""


def main():
    entries = []
    for d in DASHBOARDS:
        folder = d.folder or "."
        path = os.path.join(HERE, folder.lower(), f"{d.uid}.json") if d.folder else os.path.join(HERE, f"{d.uid}.json")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(d.dumps())
        rel = os.path.relpath(path, HERE)
        # The sidecar writes each ConfigMap key to /tmp/dashboards/<folder>/<key>.
        entry = f"  - name: grafana-dashboard-{d.uid}\n    files:\n      - {os.path.basename(rel)}={rel}\n"
        if d.folder:
            entry += f"    options:\n      annotations:\n        grafana_folder: {d.folder}\n"
        entries.append(entry)
    # The overview is the home dashboard (grafana.ini default_home_dashboard_path).
    with open(os.path.join(HERE, "kustomization.yaml"), "w") as f:
        f.write(HEADER + "".join(entries))
    print(f"wrote {len(DASHBOARDS)} dashboards")


if __name__ == "__main__":
    main()
